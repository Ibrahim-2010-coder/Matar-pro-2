function wFitText(ctx, text, weight, px, maxW, minScale = 0.72) {
  const t = String(text ?? "");
  if (!t) return { text: "", size: Math.round(px) };
  let size = px;
  ctx.font = `${weight} ${Math.round(size)}px ${W_FONT}`;
  if (ctx.measureText(t).width <= maxW) return { text: t, size: Math.round(size) };
  while (size > px * minScale) {
    size *= 0.90;
    ctx.font = `${weight} ${Math.round(size)}px ${W_FONT}`;
    if (ctx.measureText(t).width <= maxW) return { text: t, size: Math.round(size) };
  }
  let cut = t;
  while (cut.length > 1 && ctx.measureText(cut + "…").width > maxW) cut = cut.slice(0, -1);
  return { text: cut + "…", size: Math.round(size) };
}

