self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(APP_CACHE);
    /* v24: لا نستخدم cache.addAll الافتراضية لأنها تحترم HTTP cache
       (فتُرجع أيقونات قديمة من GitHub Pages). بدلًا من ذلك: نجلب كل
       مورد بـ cache: 'no-cache' كي نتخطّى HTTP cache ونحفظ المحتوى
       الجديد فعلًا، ثم نخزّنه في كاش التطبيق. فشل مورد واحد لا يوقف الكل. */
    await Promise.all(APP_SHELL.map(async (url) => {
      try {
        const res = await fetch(url, { cache: "no-cache", credentials: "omit" });
        if (res && (res.ok || res.type === "opaque")) {
          await cache.put(url, res);
        }
      } catch (e) { /* تجاهل: مورد واحد فاشل لا يكسر التثبيت */ }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  /* إصلاح ①: فلتر الشرطين معًا —
     نحذف كاشًا قديمًا فقط إذا لم يبدأ بإصدارنا الحالي وليس كاش حالة المستخدم.
     (الكاش القديم "matar-pro-v21:*" يُمسح، و"matar:state" ينجو عبر الترقيات)
     v27: كاش "matar:widget" ينجو كذلك — صورة الودجت المولّدة في الخلفية
     تظل صالحة عبر الترقيات ولا يُجبر المستخدم على انتظار توليد جديد. */
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((k) => !k.startsWith(VERSION) && k !== STATE_CACHE && k !== "matar:widget")
        .map((k) => caches.delete(k))
    );
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  let url;
  try { url = new URL(req.url); } catch (e) { return; }

  /* ── v29: بث الزحمة الحي (خدمة Esri Traffic) — شبكة حيًا حصرًا بلا تخزين؛
     كاش بلاطات الزحمة القديمة يضلّل السائق بألوان طرق لم تعد صحيحة ── */
  if (/arcgisonline\.com$/.test(url.hostname) && /traffic/i.test(url.pathname)) return;

  /* ── v45: بث الزحمة الحي من مضيف traffic.arcgis.com أيضًا — شبكة حيًا حصرًا بلا
     تخزين كي لا يضلّل السائق كاش قديم بألوان طرق لم تعد صحيحة ── */
  if (/^traffic\.arcgis\.com$/.test(url.hostname)) return;

  /* ── بلاطات الخرائط: كاش أولًا ثم شبكة، والفشل يعيد PNG شفاف (إصلاح ②) ── */
  if (isTileHost(url.hostname)) {
    event.respondWith((async () => {
      const cache = await caches.open(TILE_CACHE);
      const hit = await cache.match(req);
      if (hit) return hit;
      try {
        /* إصلاح v32 (وضع CORS الصامت): كان { mode: "cors" } يُجبر طلب
           البلاطة على التحقق من ترويسات CORS حتى عندما يطلبها <img> بنمط
           no-cors — خوادم بلا ترويسات ترفض الطلب فتظهر مربعات شفافة/مكسورة
           وقت عمل الإنترنت. الآن نترك المتصفح يحدد الوضع الافتراضي من
           الطلب نفسه، ونقبل الاستجابات opaque (type === "opaque") للتخزين
           والعرض — سلوك مطابق لتحميل الصور العادي. */
        const res = await fetch(req, { credentials: "omit" });
        if (res && (res.ok || res.type === "opaque")) { cache.put(req, res.clone()); return res; }
        return transparentTileResponse();
      } catch (e) {
        return transparentTileResponse();
      }
    })());
    return;
  }

  /* ── APIs الطقس والتوجيه: شبكة حيًا بلا تدخل (التطبيق يدير أوفلاينه بنفسه) ── */
  if (API_HOST_SUFFIXES.some((s) => url.hostname === s || url.hostname.endsWith(`.${s}`))) return;

  /* ── تنقل الصفحة: شبكة أولًا ثم الكاش (كي تصل التحديثات بسرعة).
     v22: cache.put/match يستخدمان المسار المطلق /Matar-pro-2/index.html
     ليتطابق مع ما يُخزَّن في APP_SHELL عند التثبيت. ── */
  if (req.mode === "navigate") {
    event.respondWith((async () => {
      try {
        /* إصدار 34: إجبار تخطي HTTP Cache عند جلب الصفحة نفسها — GitHub Pages
           يخدم index.html بترويسة كاش طويلة، فكان المستخدمون يتلقون النسخة
           القديمة رغم رفع الإصدار (واجهة تحميل «مجمّدة»). cache: "no-cache"
           يجبر المتصفح على التحقق من الخادم وجلب أحدث HTML دائمًا، ثم يُحدّث
           الكاش بالنسخة الجديدة — مع بقاء الاحتياط الأوفلاين سليمًا. */
        const fresh = await fetch(req, { cache: "no-cache" });
        const cache = await caches.open(APP_CACHE);
        cache.put(`${APP_BASE}index.html`, fresh.clone()).catch(() => {});
        return fresh;
      } catch (e) {
        const cache = await caches.open(APP_CACHE);
        return (await cache.match(`${APP_BASE}index.html`)) || (await cache.match(APP_BASE)) || Response.error();
      }
    })());
    return;
  }

  /* ── باقي أصول التطبيق (نفس الأصل أو CDN مسبق التخزين): كاش أولًا ── */
  if (url.origin === self.location.origin || url.hostname === "cdnjs.cloudflare.com" || url.hostname === "unpkg.com" || url.hostname === "cdn.jsdelivr.net") {
    event.respondWith((async () => {
      const cache = await caches.open(APP_CACHE);
      const hit = await cache.match(req, { ignoreVary: true });
      if (hit) return hit;
      try {
        const res = await fetch(req);
        if (res && (res.ok || res.type === "opaque")) cache.put(req, res.clone()).catch(() => {});
        return res;
      } catch (e) {
        return Response.error();
      }
    })());
  }
});

