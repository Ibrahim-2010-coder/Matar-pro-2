  const pillH = Math.round(H * 0.135);
  const pillW = W - pad * 2;
  const pillX = pad;
  const pillY = H - Math.round(H * 0.038) - pillH;
  const pillR = Math.max(14, Math.min(24, Math.round(minWH * 0.0204))); /* 22px عند 1080 */
  const pillMidY = pillY + pillH / 2;
  wRr(ctx, pillX, pillY, pillW, pillH, pillR);
  ctx.fillStyle = "rgba(255,255,255,0.14)";
  ctx.fill();
  const sheen = ctx.createLinearGradient(0, pillY, 0, pillY + pillH);
  sheen.addColorStop(0, "rgba(255,255,255,0.10)");
  sheen.addColorStop(0.55, "rgba(255,255,255,0)");
  wRr(ctx, pillX, pillY, pillW, pillH, pillR);
  ctx.fillStyle = sheen;
  ctx.fill();
  const lineW = Math.max(1, Math.round(minWH / 720));
  wRr(ctx, pillX + 0.5, pillY + 0.5, pillW - 1, pillH - 1, Math.max(1, pillR - 1));
  ctx.lineWidth = lineW;
  ctx.strokeStyle = "rgba(255,255,255,0.25)";
  ctx.stroke();

  /* ── شعار التطبيق بالزاوية: قطرة + «مَطَر برو | Matar Pro» ── */
  const innerPad = Math.round(pillH * 0.13);
  const dropR = Math.round(pillH * 0.165);
  const brandGap = Math.round(pillH * 0.12);
  const pipeGap = Math.round(pillH * 0.10);
  const arFont = Math.round(pillH * 0.205);
  const enFont = Math.round(pillH * 0.165);
  const arName = "مَطَر برو", enName = "Matar Pro";
  ctx.font = `700 ${arFont}px ${W_FONT}`;
  const arW = ctx.measureText(arName).width;
  ctx.font = `700 ${enFont}px ${W_FONT}`;
  const enW = ctx.measureText(enName).width;
  ctx.font = `400 ${enFont}px ${W_FONT}`;
  const pipeW = ctx.measureText("|").width;
  const brandW = dropR * 2 + brandGap + arW + pipeGap + pipeW + pipeGap + enW;
  const gapBrand = Math.round(pillH * 0.16);
  let indStart, indEnd;
  if (ar) {
    indStart = pillX + innerPad;
    indEnd = pillX + pillW - innerPad - brandW - gapBrand;
  } else {
    indStart = pillX + innerPad + brandW + gapBrand;
    indEnd = pillX + pillW - innerPad;
  }
  const dropCx = ar ? pillX + pillW - innerPad - dropR : pillX + innerPad + dropR;
  wBrandDrop(ctx, dropCx, pillMidY, dropR);
  ctx.textBaseline = "middle";
  if (ar) {
    ctx.font = `700 ${arFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.96)";
    ctx.textAlign = "right";
    ctx.fillText(arName, dropCx - dropR - brandGap, pillMidY);
    const pipeX = dropCx - dropR - brandGap - arW - pipeGap;
    ctx.font = `400 ${enFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.35)";
    ctx.fillText("|", pipeX, pillMidY);
    ctx.font = `700 ${enFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.85)";
    ctx.fillText(enName, pipeX - pipeGap, pillMidY);
  } else {
    ctx.font = `700 ${enFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.96)";
    ctx.textAlign = "left";
    ctx.fillText(enName, dropCx + dropR + brandGap, pillMidY);
    const pipeX = dropCx + dropR + brandGap + enW + pipeGap;
    ctx.font = `400 ${enFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.35)";
    ctx.fillText("|", pipeX, pillMidY);
    ctx.font = `700 ${arFont}px ${W_FONT}`;
    ctx.fillStyle = "rgba(255,255,255,0.85)";
    ctx.fillText(arName, pipeX + pipeGap, pillMidY);
  }

  /* ── 3 مؤشرات سريعة حسب نوع الودجت مفصولة بخطوط رفيعة ── */
  const pct = ar ? "٪" : "%";
  const at = (arr, i) => (arr && arr[i] != null ? arr[i] : null);
  const rainProb = at(hr && hr.precipitation_probability, kNow)
    ?? (dy && dy.precipitation_probability_max ? dy.precipitation_probability_max[0] : null)
    ?? null;
  const vis = at(hr && hr.visibility, kNow);
